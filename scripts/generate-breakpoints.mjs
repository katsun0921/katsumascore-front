import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const rootDir = path.resolve(__dirname, '..')

const sourcePath = path.join(rootDir, 'src/styles/tokens/breakpoints.json')
const cssOutputPath = path.join(rootDir, 'src/styles/generated/breakpoints.css')
const scssOutputPath = path.join(rootDir, 'src/styles/scss/global/variable/_breakpoints.scss')

const source = JSON.parse(await readFile(sourcePath, 'utf8'))
const entries = Object.entries(source)

const cssLines = [
  '/* This file is auto-generated by scripts/generate-breakpoints.mjs. */',
  '/* Do not edit this file directly. Update src/styles/tokens/breakpoints.json instead. */',
  '@theme inline {',
  ...entries.map(([name, value]) => `  --breakpoint-${name}: ${value};`),
  '}',
  '',
]

const scssLines = [
  '// This file is auto-generated by scripts/generate-breakpoints.mjs.',
  '// Do not edit this file directly. Update src/styles/tokens/breakpoints.json instead.',
  ...entries.map(([name, value]) => `$breakpoint-${name}: ${value} !default;`),
  '',
]

await mkdir(path.dirname(cssOutputPath), { recursive: true })
await mkdir(path.dirname(scssOutputPath), { recursive: true })

await writeFile(cssOutputPath, `${cssLines.join('\n')}`, 'utf8')
await writeFile(scssOutputPath, `${scssLines.join('\n')}`, 'utf8')

console.log(`Generated ${path.relative(rootDir, cssOutputPath)}`)
console.log(`Generated ${path.relative(rootDir, scssOutputPath)}`)
